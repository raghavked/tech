const NUMBER_WORDS = [
  "no",
  "one",
  "two",
  "three",
  "four",
  "five",
  "six",
  "seven",
  "eight",
  "nine",
  "ten",
];

/** "five" for 5 and "12" past ten; capitalised when it starts the sentence. */
export const numberWords = (n: number, capital = false): string => {
  const w = NUMBER_WORDS[n] ?? String(n);
  return capital ? w.charAt(0).toUpperCase() + w.slice(1) : w;
};

